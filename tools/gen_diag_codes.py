#!/usr/bin/env python3
"""Generate the diag code tables from firmware/components/diag/diag_codes.yaml.

Writes:
  firmware/components/diag/include/diag_codes.hpp   firmware: Source, Code, slot table
  firmware/components/diag/host/diag_codes.py       host: lookup table
  docs/protocol/diag-codes.md                       the code table between marker comments

Usage:
  python tools/gen_diag_codes.py           regenerate
  python tools/gen_diag_codes.py --check   exit 1 if any generated file is stale (CI)

Needs PyYAML.
"""

from __future__ import annotations

import argparse
import keyword
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DIAG_DIR = ROOT / "firmware" / "components" / "diag"
YAML_PATH = DIAG_DIR / "diag_codes.yaml"
HPP_PATH = DIAG_DIR / "include" / "diag_codes.hpp"
PY_PATH = DIAG_DIR / "host" / "diag_codes.py"
README_PATH = ROOT / "docs" / "protocol" / "diag-codes.md"

README_BEGIN = "<!-- diag-codes:begin (generated by tools/gen_diag_codes.py) -->"
README_END = "<!-- diag-codes:end -->"

SEVERITIES = {"error": ("Error", 1), "warning": ("Warning", 2)}
KINDS = {"record": "Record", "counter": "Counter"}
IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")
SOURCE_IDENT = re.compile(r"^[a-z][a-z0-9_]*$")
MAX_SLOTS = 254  # 0xFF is the "no next page" marker in GetEntries


class SpecError(Exception):
    pass


def pascal(snake: str) -> str:
    return "".join(part.capitalize() for part in snake.split("_"))


def load_spec() -> tuple[dict[str, int], list[dict]]:
    with YAML_PATH.open(encoding="utf-8") as f:
        doc = yaml.safe_load(f)
    if not isinstance(doc, dict) or "sources" not in doc or "codes" not in doc:
        raise SpecError("diag_codes.yaml needs top-level 'sources' and 'codes'")

    sources: dict[str, int] = doc["sources"]
    seen_ids: dict[int, str] = {}
    for name, sid in sources.items():
        if not SOURCE_IDENT.match(str(name)) or keyword.iskeyword(name):
            raise SpecError(f"source name '{name}' must be snake_case")
        if not isinstance(sid, int) or not 0x01 <= sid <= 0xFE:
            raise SpecError(f"source '{name}': id must be 0x01..0xFE")
        if sid in seen_ids:
            raise SpecError(f"source '{name}': id 0x{sid:02X} already used by '{seen_ids[sid]}'")
        seen_ids[sid] = name

    codes: list[dict] = doc["codes"] or []
    seen_codes: set[tuple[str, int]] = set()
    seen_names: set[tuple[str, str]] = set()
    for c in codes:
        where = f"code {c.get('source')}/{c.get('name')}"
        for key in ("source", "code", "name", "severity", "kind", "description"):
            if key not in c:
                raise SpecError(f"{where}: missing '{key}'")
        if c["source"] not in sources:
            raise SpecError(f"{where}: unknown source")
        if not isinstance(c["code"], int) or not 0x0001 <= c["code"] <= 0xFFFF:
            raise SpecError(f"{where}: code must be 0x0001..0xFFFF")
        if not IDENT.match(c["name"]) or not c["name"][0].isupper():
            raise SpecError(f"{where}: name must be PascalCase")
        if c["severity"] not in SEVERITIES:
            raise SpecError(f"{where}: severity must be one of {sorted(SEVERITIES)}")
        if c["kind"] not in KINDS:
            raise SpecError(f"{where}: kind must be one of {sorted(KINDS)}")
        c.setdefault("clears", False)
        c.setdefault("retired", False)
        if not isinstance(c["clears"], bool) or not isinstance(c["retired"], bool):
            raise SpecError(f"{where}: 'clears' and 'retired' must be true/false")
        if c["kind"] == "counter":
            if c["clears"]:
                raise SpecError(f"{where}: counter codes cannot clear")
            if "arg0" in c or "arg1" in c:
                raise SpecError(f"{where}: counter codes carry no args")
        else:
            for arg in ("arg0", "arg1"):
                if arg not in c:
                    raise SpecError(f"{where}: missing '{arg}' (use 'unused')")
        key = (c["source"], c["code"])
        if key in seen_codes:
            raise SpecError(f"{where}: code 0x{c['code']:04X} already used in source '{c['source']}'")
        seen_codes.add(key)
        name_key = (c["source"], c["name"])
        if name_key in seen_names:
            raise SpecError(f"{where}: name already used in source '{c['source']}'")
        seen_names.add(name_key)

    live = [c for c in codes if not c["retired"]]
    if len(live) > MAX_SLOTS:
        raise SpecError(f"{len(live)} live codes; at most {MAX_SLOTS} fit the slot index")
    return sources, codes


def cpp_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_hpp(sources: dict[str, int], codes: list[dict]) -> str:
    live = [c for c in codes if not c["retired"]]
    out: list[str] = []
    w = out.append
    w("#pragma once")
    w("")
    w("// GENERATED by tools/gen_diag_codes.py from firmware/components/diag/diag_codes.yaml.")
    w("// Do not edit by hand: edit the YAML and rerun the script.")
    w("//")
    w("// Pure C++ with no ESP-IDF dependency (the host unit tests include it).")
    w("")
    w("#include <array>")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("namespace diag {")
    w("")
    w("/// The component that reports a code (the `source` byte on the wire).")
    w("enum class Source : uint8_t {")
    for name, sid in sources.items():
        w(f"    {pascal(name)} = 0x{sid:02X},")
    w("};")
    w("")
    w("enum class Severity : uint8_t {")
    w("    Error = 1,")
    w("    Warning = 2,")
    w("};")
    w("")
    w("/// Record codes go through DIAG_ERROR / DIAG_WARN; counter codes through DIAG_COUNT.")
    w("enum class CodeKind : uint8_t {")
    w("    Record = 0,")
    w("    Counter = 1,")
    w("};")
    w("")
    w("/// One code: its slot in the diag table and its fixed attributes.")
    w("struct Code {")
    w("    uint8_t slot;       ///< Dense index into the diag slot table")
    w("    Source source;")
    w("    uint16_t code;      ///< Unique within its source")
    w("    Severity severity;")
    w("    CodeKind kind;")
    w("    bool clears;        ///< Has an `active` bit cleared by DIAG_CLEAR on recovery")
    w("};")
    w("")
    w("namespace codes {")
    by_source: dict[str, list[tuple[int, dict]]] = {}
    for slot, c in enumerate(live):
        by_source.setdefault(c["source"], []).append((slot, c))
    for src in sources:
        entries = by_source.get(src)
        if not entries:
            continue
        w("")
        w(f"namespace {src} {{")
        for slot, c in entries:
            w(f"/// {c['description']}")
            if c["kind"] == "record":
                w(f"/// arg0: {c['arg0']}. arg1: {c['arg1']}.")
            sev = SEVERITIES[c["severity"]][0]
            kind = KINDS[c["kind"]]
            clears = "true" if c["clears"] else "false"
            w(
                f"inline constexpr ::diag::Code k{c['name']}{{{slot}, ::diag::Source::{pascal(src)}, "
                f"0x{c['code']:04X}, ::diag::Severity::{sev}, ::diag::CodeKind::{kind}, {clears}}};"
            )
        w(f"}} // namespace {src}")
    w("")
    w("} // namespace codes")
    w("")
    w(f"inline constexpr size_t kSlotCount = {len(live)};")
    w("")
    w("/// Every live code, indexed by slot.")
    w("inline constexpr std::array<Code, kSlotCount> kCodeTable = {{")
    for c in live:
        w(f"    codes::{c['source']}::k{c['name']},")
    w("}};")
    w("")
    w("} // namespace diag")
    w("")
    return "\n".join(out)


def gen_py(sources: dict[str, int], codes: list[dict]) -> str:
    out: list[str] = []
    w = out.append
    w('"""diag code table for host tools.')
    w("")
    w("GENERATED by tools/gen_diag_codes.py from firmware/components/diag/diag_codes.yaml.")
    w("Do not edit by hand.")
    w('"""')
    w("")
    w("SEVERITIES = {1: \"error\", 2: \"warning\"}")
    w("")
    w("SOURCES = {")
    for name, sid in sources.items():
        w(f"    0x{sid:02X}: {name!r},")
    w("}")
    w("")
    w("# (source id, code) -> attributes. Retired codes stay so old logs still decode.")
    w("CODES = {")
    for c in codes:
        sid = sources[c["source"]]
        w(f"    (0x{sid:02X}, 0x{c['code']:04X}): {{")
        w(f"        \"name\": {c['name']!r},")
        w(f"        \"severity\": {c['severity']!r},")
        w(f"        \"kind\": {c['kind']!r},")
        w(f"        \"clears\": {c['clears']!r},")
        w(f"        \"arg0\": {c.get('arg0')!r},")
        w(f"        \"arg1\": {c.get('arg1')!r},")
        w(f"        \"description\": {c['description']!r},")
        w(f"        \"retired\": {c['retired']!r},")
        w("    },")
    w("}")
    w("")
    w("")
    w("def describe(source: int, code: int) -> str:")
    w('    """Return "source.Name" for a (source, code) pair, or a hex placeholder."""')
    w("    src = SOURCES.get(source, f\"source_0x{source:02X}\")")
    w("    info = CODES.get((source, code))")
    w("    name = info[\"name\"] if info else f\"code_0x{code:04X}\"")
    w("    return f\"{src}.{name}\"")
    w("")
    return "\n".join(out)


def md_cell(s: str | None) -> str:
    return (s or "").replace("|", "\\|")


def gen_readme_table(sources: dict[str, int], codes: list[dict]) -> str:
    rows = [
        README_BEGIN,
        "",
        "| Source | Code | Name | Severity | Kind | Clears | arg0 | arg1 | Description |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for c in codes:
        sid = sources[c["source"]]
        name = f"~~{c['name']}~~ (retired)" if c["retired"] else c["name"]
        rows.append(
            f"| `{c['source']}` (0x{sid:02X}) | 0x{c['code']:04X} | {name} | {c['severity']} | {c['kind']} | "
            f"{'yes' if c['clears'] else 'no'} | {md_cell(c.get('arg0', '-'))} | {md_cell(c.get('arg1', '-'))} | "
            f"{md_cell(c['description'])} |"
        )
    rows.append("")
    rows.append(README_END)
    return "\n".join(rows)


def splice_readme(current: str, table: str) -> str:
    begin = current.find(README_BEGIN)
    end = current.find(README_END)
    if begin < 0 or end < 0 or end < begin:
        raise SpecError(f"{README_PATH.relative_to(ROOT)} needs the marker lines:\n  {README_BEGIN}\n  {README_END}")
    return current[:begin] + table + current[end + len(README_END):]


def normalize(text: str) -> str:
    return text.replace("\r\n", "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a generated file is stale; write nothing")
    args = parser.parse_args()

    try:
        sources, codes = load_spec()
        readme_now = normalize(README_PATH.read_text(encoding="utf-8")) if README_PATH.exists() else ""
        outputs = {
            HPP_PATH: gen_hpp(sources, codes),
            PY_PATH: gen_py(sources, codes),
            README_PATH: splice_readme(readme_now, gen_readme_table(sources, codes)),
        }
    except SpecError as e:
        print(f"gen_diag_codes: {e}", file=sys.stderr)
        return 2

    stale = []
    for path, text in outputs.items():
        current = normalize(path.read_text(encoding="utf-8")) if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as f:
                f.write(text)

    for path in stale:
        verb = "stale" if args.check else "updated"
        print(f"{verb}: {path.relative_to(ROOT).as_posix()}")
    if args.check and stale:
        print("Run `python tools/gen_diag_codes.py` and commit the result.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
