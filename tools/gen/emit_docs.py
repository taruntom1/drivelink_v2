"""Emit the generated parts of docs/protocol/.

registry.md and diag-codes.md are hand-written files with one generated block
between marker comments. docs/protocol/types/<type>.md is generated whole.
"""

from __future__ import annotations

from model import SpecError

REGISTRY_DOC = "docs/protocol/registry.md"
DIAG_DOC = "docs/protocol/diag-codes.md"
TYPES_DOC_DIR = "docs/protocol/types"

DIRECTION_TEXT = {"host_to_esp": "host to ESP", "esp_to_host": "ESP to host", "both": "either way"}

REGISTRY_BEGIN = "<!-- registry:begin (generated by tools/gen/gen.py) -->"
REGISTRY_END = "<!-- registry:end -->"
DIAG_BEGIN = "<!-- diag-codes:begin (generated by tools/gen/gen.py) -->"
DIAG_END = "<!-- diag-codes:end -->"

# Used when the file does not exist yet (a fresh output directory).
REGISTRY_TEMPLATE = f"""# Registry

The MSG_TYPEs and stream channel ranges of the wire protocol. The tables are generated from `protocol/defs/registry.yaml` by `tools/gen/gen.py`; edit the YAML and regenerate, never the tables. How the definitions work is in [definitions.md](definitions.md), and the frame and the MSG_TYPE classes are in [framing.md](framing.md).

A legacy entry is the old protocol of a manager that a later overhaul step ports. The step removes the entry with the manager. The time ping (0x02 / 0x42) joins in F8; the legacy IMU response holds 0x42 until F6 removes the IMU manager.

{REGISTRY_BEGIN}
{REGISTRY_END}
"""

DIAG_TEMPLATE = f"""# diag codes

Every code the firmware can report through `diag` (events on MSG_TYPE `0xC0`, entries from the `0x23` query). The table is generated from `protocol/defs/diag_codes.yaml` by `tools/gen/gen.py`; edit the YAML and regenerate, never the table.

{DIAG_BEGIN}
{DIAG_END}
"""


def md_cell(s: str | None) -> str:
    return (s or "").replace("|", "\\|")


def splice(current: str, template: str, begin: str, end: str, block: str, name: str) -> str:
    """Replace the text between the marker lines of `current` with `block`."""
    text = current if current else template
    b = text.find(begin)
    e = text.find(end)
    if b < 0 or e < 0 or e < b:
        raise SpecError(f"{name} needs the marker lines:\n  {begin}\n  {end}")
    return text[:b] + block + text[e + len(end):]


# -- registry.md ---------------------------------------------------------------


def registry_block(defs: dict, hash_value: int) -> str:
    reg = defs["registry"]
    rows = [
        REGISTRY_BEGIN,
        "",
        f"Descriptor hash: `0x{hash_value:08X}` (CRC-32 over all definitions; see [definitions.md](definitions.md)).",
        "",
        "## MSG_TYPEs",
        "",
        "| Value | Name | Class | Direction | Legacy | Use |",
        "|---|---|---|---|---|---|",
    ]
    for m in reg["msg_types"]:
        legacy = f"removed in {m['legacy']}" if m["legacy"] else ""
        rows.append(
            f"| 0x{m['value']:02X} | `{m['name']}` | {m['class']} | {DIRECTION_TEXT[m['direction']]} | {legacy} | "
            f"{md_cell(m['description'])} |"
        )
    rows += [
        "",
        "## Stream channel ranges",
        "",
        "| Range | Channels | Direction | Usable | Use |",
        "|---|---|---|---|---|",
    ]
    for r in reg["channel_ranges"]:
        usable_last = r["first"] + r["usable_count"] - 1
        rows.append(
            f"| `{r['name']}` | 0x{r['first']:02X}-0x{r['last']:02X} | {DIRECTION_TEXT[r['direction']]} | "
            f"{r['usable_count']} (0x{r['first']:02X}-0x{usable_last:02X}) | {md_cell(r['description'])} |"
        )
    rows += ["", f"The system type id is 0x{reg['system_type_id']:02X}.", "", REGISTRY_END]
    return "\n".join(rows)


# -- diag-codes.md -------------------------------------------------------------


def diag_block(defs: dict) -> str:
    source_ids = {s["name"]: s["id"] for s in defs["diag"]["sources"]}
    rows = [
        DIAG_BEGIN,
        "",
        "| Source | Code | Name | Severity | Kind | Clears | arg0 | arg1 | Description |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for c in defs["diag"]["codes"]:
        sid = source_ids[c["source"]]
        name = f"~~{c['name']}~~ (retired)" if c["retired"] else c["name"]
        arg0 = "-" if c["arg0"] is None else c["arg0"]
        arg1 = "-" if c["arg1"] is None else c["arg1"]
        rows.append(
            f"| `{c['source']}` (0x{sid:02X}) | 0x{c['code']:04X} | {name} | {c['severity']} | {c['kind']} | "
            f"{'yes' if c['clears'] else 'no'} | {md_cell(arg0)} | {md_cell(arg1)} | "
            f"{md_cell(c['description'])} |"
        )
    rows.append("")
    rows.append(DIAG_END)
    return "\n".join(rows)


# -- types/<type>.md -----------------------------------------------------------


def value_text(item: dict, key: str) -> str:
    v = item[key]
    if v is None:
        return ""
    if item["type"] == "f32":
        return f"{v:.9g}"
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def range_text(item: dict) -> str:
    if not item["has_min"] and not item["has_max"]:
        return ""
    lo = value_text(item, "min") if item["has_min"] else ""
    hi = value_text(item, "max") if item["has_max"] else ""
    return f"{lo} .. {hi}".strip()


def arg_list(args: list[dict]) -> str:
    return ", ".join(f"{a['name']}: {a['type']}" + (f" ({a['unit']})" if a["unit"] else "") for a in args) or "none"


def type_doc_path(t: dict) -> str:
    return f"{TYPES_DOC_DIR}/{t['type']}.md"


def type_doc(t: dict) -> str:
    live = [i for i in t["items"] if not i["retired"]]
    retired = [i for i in t["items"] if i["retired"]]
    out = [
        f"# {t['type']}",
        "",
        "<!-- generated by tools/gen/gen.py from the type's YAML file in protocol/defs/; do not edit -->",
        "",
        f"Type id `0x{t['type_id']:02X}`. Loops: {', '.join(t['loops']) or 'none (the system items are applied on the config task)'}.",
    ]
    if t["description"]:
        out += ["", t["description"]]

    for kind, title in (("param", "Params"), ("signal", "Signals"), ("input", "Inputs")):
        items = [i for i in live if i["kind"] == kind]
        if not items:
            continue
        out += [
            "",
            f"## {title}",
            "",
            "| Id | Name | Type | Unit | Range | Default | Flags | Description |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for i in items:
            vtype = i["type"]
            if i["values"]:
                vtype = "enum (" + ", ".join(f"{v['name']}={v['value']}" for v in i["values"]) + ")"
            flags = list(i["flags"])
            if i["ref"]:
                flags.append(f"ref:{i['ref']}")
            out.append(
                f"| 0x{i['id']:04X} | `{i['name']}` | {md_cell(vtype)} | {md_cell(i['unit'])} | {range_text(i)} | "
                f"{value_text(i, 'default')} | {', '.join(flags)} | {md_cell(i['description'])} |"
            )

    actions = [i for i in live if i["kind"] == "action"]
    if actions:
        out += [
            "",
            "## Actions",
            "",
            "| Id | Name | Runs in | Args | Results | Blob | Description |",
            "|---|---|---|---|---|---|---|",
        ]
        for i in actions:
            out.append(
                f"| 0x{i['id']:04X} | `{i['name']}` | {i['runs_in']} | {md_cell(arg_list(i['args']))} | "
                f"{md_cell(arg_list(i['results']))} | {i['blob']} | {md_cell(i['description'])} |"
            )

    if retired:
        out += ["", "## Retired ids", "", "These ids are never reused.", ""]
        out += [f"- 0x{i['id']:04X} ~~{i['name']}~~" for i in retired]
    return "\n".join(out) + "\n"
