"""Tests for tools/gen. Run: python -m unittest discover -s tools/gen/tests

Stdlib only (the generator itself needs PyYAML). The golden fixtures are in
tests/fixtures: a registry, a small diag file, a system type and the module types
(fixture.full, fixture.sensor, and the wiring set actuator.fixture,
feedback.fixture and fixture.wired).
"""

from __future__ import annotations

import contextlib
import io
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import descriptor_hash  # noqa: E402
import gen  # noqa: E402
import model  # noqa: E402

FIXTURES = HERE / "fixtures"
GEN_DIR = "protocol/include/drivelink/protocol/gen"


class TempCase(unittest.TestCase):
    """A fresh copy of the fixtures per test, plus an output directory."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        root = Path(self._tmp.name)
        self.defs = root / "defs"
        self.out = root / "out"
        shutil.copytree(FIXTURES, self.defs)
        self.out.mkdir()

    def mutate(self, file: str, old: str, new: str) -> None:
        path = self.defs / file
        text = path.read_text(encoding="utf-8")
        self.assertIn(old, text, f"test bug: {old!r} not in {file}")
        path.write_text(text.replace(old, new, 1), encoding="utf-8", newline="\n")

    def run_gen(self, check: bool = False) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = gen.run(self.defs, self.out, check)
        return code, out.getvalue(), err.getvalue()

    def read(self, rel: str) -> str:
        return (self.out / rel).read_text(encoding="utf-8")

    def hash(self) -> int:
        return descriptor_hash.descriptor_hash(model.load_defs(self.defs))

    def assertSpecError(self, *parts: str) -> None:
        with self.assertRaises(model.SpecError) as cm:
            model.load_defs(self.defs)
        for p in parts:
            self.assertIn(p, str(cm.exception))


class GoldenOutput(TempCase):
    def setUp(self) -> None:
        super().setUp()
        code, _, err = self.run_gen()
        self.assertEqual(code, 0, err)

    def test_files_written_with_lf_and_header(self) -> None:
        names = [
            f"{GEN_DIR}/registry.hpp",
            f"{GEN_DIR}/diag_codes.hpp",
            f"{GEN_DIR}/types.hpp",
            f"{GEN_DIR}/type_fixture_full.hpp",
            f"{GEN_DIR}/type_fixture_sensor.hpp",
            f"{GEN_DIR}/type_system.hpp",
            f"{GEN_DIR}/type_actuator_fixture.hpp",
            f"{GEN_DIR}/type_feedback_fixture.hpp",
            f"{GEN_DIR}/type_fixture_wired.hpp",
        ]
        for rel in names:
            raw = (self.out / rel).read_bytes()
            self.assertNotIn(b"\r", raw, rel)
            text = raw.decode("utf-8")
            self.assertIn("GENERATED by tools/gen/gen.py", text, rel)
            self.assertIn("do not edit", text.lower(), rel)
            self.assertTrue(text.startswith("#pragma once\n"), rel)
            self.assertTrue(text.endswith("\n"), rel)

