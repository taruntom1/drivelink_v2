class CheckMode(TempCase):
    def test_check_fails_on_fresh_output_and_passes_after_generate(self) -> None:
        code, stdout, _ = self.run_gen(check=True)
        self.assertEqual(code, 1)
        self.assertIn("stale: ", stdout)
        self.assertFalse((self.out / GEN_DIR / "registry.hpp").exists())  # --check writes nothing
        self.assertEqual(self.run_gen()[0], 0)
        self.assertEqual(self.run_gen(check=True)[0], 0)

    def test_check_ignores_crlf(self) -> None:
        self.run_gen()
        for path in (self.out / GEN_DIR).glob("*.hpp"):
            path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))
        self.assertEqual(self.run_gen(check=True)[0], 0)

    def test_check_fails_when_a_file_changes(self) -> None:
        self.run_gen()
        path = self.out / GEN_DIR / "registry.hpp"
        path.write_text(path.read_text(encoding="utf-8") + "// edited\n", encoding="utf-8", newline="\n")
        code, stdout, _ = self.run_gen(check=True)
        self.assertEqual(code, 1)
        self.assertIn("stale: protocol/include/drivelink/protocol/gen/registry.hpp", stdout)

    def test_check_fails_when_a_definition_changes(self) -> None:
        self.run_gen()
        self.mutate("fixture.sensor.yaml", "unit: m", "unit: cm")
        self.assertEqual(self.run_gen(check=True)[0], 1)

    def test_check_reports_orphans(self) -> None:
        self.run_gen()
        (self.defs / "fixture.sensor.yaml").unlink()
        code, stdout, _ = self.run_gen(check=True)
        self.assertEqual(code, 1)
        self.assertIn("orphan: docs/protocol/types/fixture.sensor.md", stdout)
        self.assertEqual(self.run_gen()[0], 0)
        self.assertEqual(self.run_gen(check=True)[0], 0)

    def test_spec_error_exits_2(self) -> None:
        self.mutate("registry.yaml", "value: 0x41", "value: 0x01")
        code, _, err = self.run_gen(check=True)
        self.assertEqual(code, 2)
        self.assertIn("registry.yaml", err)


class DescriptorHash(TempCase):
    def test_stable(self) -> None:
        self.assertEqual(self.hash(), self.hash())
        other = Path(self._tmp.name) / "defs2"
        shutil.copytree(self.defs, other)
        self.assertEqual(descriptor_hash.descriptor_hash(model.load_defs(other)), self.hash())

    def test_ignores_comments_and_key_order(self) -> None:
        before = self.hash()
        self.mutate("fixture.sensor.yaml", "type: fixture.sensor\n", "# a comment\ntype: fixture.sensor\n")
        self.mutate("fixture.sensor.yaml", "{id: 0x0100, kind: signal, name: value, type: f32, unit: m}",
                    "{unit: m, type: f32, name: value, kind: signal, id: 0x0100}")
        self.assertEqual(self.hash(), before)

    def test_changes_with_every_kind_of_definition(self) -> None:
        base = self.hash()
        changes = [
            ("registry.yaml", "{name: fx_event,     value: 0xC0,", "{name: fx_event,     value: 0xC2,"),
            ("registry.yaml", "legacy: F9}\n  - {name: fx_old_setpt", "legacy: F8}\n  - {name: fx_old_setpt"),
            ("registry.yaml", 'description: "A command."', 'description: "A command!"'),
            ("registry.yaml", "first: 0x81, last: 0x8F", "first: 0x81, last: 0x8E"),
            ("diag_codes.yaml", "name: Broken", "name: Broken2"),
            ("diag_codes.yaml", "description: Something was dropped.", "description: Something got dropped."),
            ("fixture.sensor.yaml", "unit: m", "unit: cm"),
            ("fixture.sensor.yaml", "type_id: 0x02", "type_id: 0x06"),
            ("fixture.sensor.yaml", "loops: [sensor]", "loops: [sensor, control]"),
            ("fixture.full.yaml", "default: 1.5", "default: 1.25"),
            ("fixture.full.yaml", "min: -100", "min: -101"),
            ("fixture.full.yaml", "default: b_mode", "default: c_mode"),
            ("fixture.full.yaml", "c_mode: 2", "c_mode: 3"),
            ("fixture.full.yaml", "flags: [locked_while_armed]", "flags: []"),
            ("fixture.full.yaml", "ref: actuator", "ref: feedback"),
            ("fixture.full.yaml", "runs_in: paused", "runs_in: loop"),
            ("fixture.full.yaml", "{name: mask, type: u8}", "{name: mask, type: u16}"),
            ("fixture.full.yaml", "blob: out", "blob: both"),
            ("fixture.full.yaml", "name: old_thing", "name: older_thing"),
            ("fixture.full.yaml", "testgen: true", "testgen: false"),
            ("system.yaml", "default: 50", "default: 60"),
            ("fixture.wired.yaml", "ref: actuator, ref_order: after", "ref: actuator"),
            ("fixture.wired.yaml", "name: pin_a, type: u8, flags: [reboot_required], gpio: true",
             "name: pin_a, type: u8, flags: [reboot_required]"),
            ("system.yaml", "unit: s}", "unit: ms}"),
        ]
        seen = {base}
        for file, old, new in changes:
            with self.subTest(file=file, change=new):
                shutil.rmtree(self.defs)
                shutil.copytree(FIXTURES, self.defs)
                self.mutate(file, old, new)
                h = self.hash()
                self.assertNotEqual(h, base)
                seen.add(h)

    def test_is_crc32_of_canonical_json(self) -> None:
        import json
        import zlib

        defs = model.load_defs(self.defs)
        text = json.dumps({"registry": defs["registry"], "diag": defs["diag"], "types": defs["types"]},
                          sort_keys=True, separators=(",", ":"))
        self.assertEqual(descriptor_hash.descriptor_hash(defs), zlib.crc32(text.encode()) & 0xFFFFFFFF)


