"""Emit the C++ headers under protocol/include/drivelink/protocol/gen/.

Each function returns the text of one file. All text uses "\\n" line ends.
"""

from __future__ import annotations

from model import KINDS, SEVERITIES, pascal, descriptor_min_payload

GEN_DIR = "protocol/include/drivelink/protocol/gen"

DIRECTION_TEXT = {"host_to_esp": "host to ESP", "esp_to_host": "ESP to host", "both": "either way",
                  "host_to_agent": "host to agent", "agent_to_host": "agent to host"}
KIND_ENUM = {"param": "Param", "signal": "Signal", "input": "Input", "action": "Action"}
TYPE_ENUM = {"bool": "Bool", "u8": "U8", "u16": "U16", "u32": "U32", "i32": "I32", "f32": "F32", "enum": "Enum", "none": "None"}
FLAG_ENUM = {
    "reboot_required": "RebootRequired",
    "persist": "Persist",
    "read_only": "ReadOnly",
    "locked_while_armed": "LockedWhileArmed",
    "testgen": "Testgen",
    "gpio": "Gpio",
    "ref_ticks_after": "RefTicksAfter",
    "tune": "Tune",
}
LOOP_ENUM = {"realtime": "Realtime", "non_realtime": "NonRealtime"}
PLACEMENT_ENUM = {None: "None", "loop": "Loop", "paused": "Paused"}
BLOB_ENUM = {"none": "None", "in": "In", "out": "Out", "both": "Both"}


def cpp_string(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f'"{out}"'


def header(sources: str) -> list[str]:
    return [
        "#pragma once",
        "",
        f"// GENERATED by tools/gen/gen.py from {sources}.",
        "// Do not edit by hand: edit the YAML and rerun `python tools/gen/gen.py`.",
        "//",
        "// Pure C++20 with no ESP-IDF dependency.",
        "",
    ]


def finish(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


# -- registry.hpp --------------------------------------------------------------


def gen_registry(defs: dict, hash_value: int) -> str:
    reg = defs["registry"]
    msgs = reg["msg_types"]
    out = header("protocol/defs/registry.yaml (and the other files in protocol/defs/ for the hash)")
    w = out.append
    w("#include <array>")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w('#include "drivelink/protocol/framing.hpp"')
    w("")
    w("namespace drivelink::protocol::defs {")
    w("")
    w("/// Type id reserved for the system items.")
    w(f"inline constexpr uint8_t kSystemTypeId = 0x{reg['system_type_id']:02X};")
    w(f"inline constexpr uint8_t kLoopTypeId = 0x{reg['loop_type_id']:02X};")
    w("")
    w("/// CRC-32 over all definitions (registry, diag codes, module types); see docs/protocol/definitions.md.")
    w(f"inline constexpr uint32_t kDescriptorHash = 0x{hash_value:08X};")
    w("")
    for name, values in reg["wire_enums"].items():
        w(f"enum class {name} : uint8_t {{")
        for key, value in values.items():
            w(f"    {key} = {value},")
        w("};")
        w("")
    w(f"inline constexpr size_t kDescriptorMinPayload = {descriptor_min_payload(defs)};")
    w("namespace msg {")
    for m in msgs:
        text = f" {m['description']}" if m["description"] else ""
        w(f"/// {m['class']}, {DIRECTION_TEXT[m['direction']]}.{text}")
        w(f"inline constexpr uint8_t k{pascal(m['name'])} = 0x{m['value']:02X};")
    w("} // namespace msg")
    w("")
    w("/// Every MSG_TYPE in the registry, by value.")
    w(f"inline constexpr std::array<uint8_t, {len(msgs)}> kAllMsgTypes = {{{{")
    for m in msgs:
        w(f"    msg::k{pascal(m['name'])},")
    w("}};")
    w("")
    w("/// Stream channel ranges: the first channel and the channel count.")
    for r in reg["channel_ranges"]:
        sym = r["symbol"]
        w(f"inline constexpr uint8_t k{sym}ChannelFirst = 0x{r['first']:02X};")
        w(f"inline constexpr size_t k{sym}ChannelCount = {r['usable_count']};")
    w("")
    w("namespace detail {")
    w("")
    w("constexpr bool msgTypesUnique()")
    w("{")
    w("    for (size_t i = 0; i < kAllMsgTypes.size(); ++i) {")
    w("        for (size_t j = i + 1; j < kAllMsgTypes.size(); ++j) {")
    w("            if (kAllMsgTypes[i] == kAllMsgTypes[j]) {")
    w("                return false;")
    w("            }")
    w("        }")
    w("    }")
    w("    return true;")
    w("}")
    w("")
    w("/// True if no registry entry lies in the `count` channels from `first`.")
    w("constexpr bool channelsClear(uint8_t first, size_t count)")
    w("{")
    w("    for (const uint8_t type : kAllMsgTypes) {")
    w("        if (type >= first && type < first + count) {")
    w("            return false;")
    w("        }")
    w("    }")
    w("    return true;")
    w("}")
    w("")
    w("} // namespace detail")
    w("")
    w("static_assert(detail::msgTypesUnique(), \"two MSG_TYPEs share a value\");")
    for m in msgs:
        n = f"msg::k{pascal(m['name'])}"
        w(f"static_assert(is{m['class'].capitalize()}({n}), \"{m['name']} is outside its class range\");")
    for r in reg["channel_ranges"]:
        sym = r["symbol"]
        first, count = f"k{sym}ChannelFirst", f"k{sym}ChannelCount"
        w(f"static_assert({first} >= kStreamMin && {first} + {count} - 1 <= kStreamMax, \"{r['name']} is outside the stream class\");")
        w(f"static_assert(detail::channelsClear({first}, {count}), \"a registry entry lies in {r['name']}\");")
    ranges = reg["channel_ranges"]
    for i, a in enumerate(ranges):
        for b in ranges[:i]:
            fa, ca = f"k{a['symbol']}ChannelFirst", f"k{a['symbol']}ChannelCount"
            fb, cb = f"k{b['symbol']}ChannelFirst", f"k{b['symbol']}ChannelCount"
            w(f"static_assert({fa} + {ca} <= {fb} || {fb} + {cb} <= {fa}, \"{a['name']} and {b['name']} overlap\");")
    w("")
    w("} // namespace drivelink::protocol::defs")
    return finish(out)


# -- diag_codes.hpp ------------------------------------------------------------


def gen_diag(defs: dict) -> str:
    sources = defs["diag"]["sources"]
    live = [c for c in defs["diag"]["codes"] if not c["retired"]]
    out = header("protocol/defs/diag_codes.yaml")
    w = out.append
    w("#include <array>")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("namespace drivelink::protocol::defs::diag {")
    w("")
    w("/// The component that reports a code (the `source` byte on the wire).")
    w("enum class Source : uint8_t {")
    for s in sources:
        w(f"    {pascal(s['name'])} = 0x{s['id']:02X},")
    w("};")
    w("")
    w("enum class Severity : uint8_t {")
    w("    Error = 1,")
    w("    Warning = 2,")
    w("};")
    w("")
    w("/// Record codes go through DIAG_ERROR / DIAG_WARN; counter codes through DIAG_COUNT.")
    w("enum class CodeKind : uint8_t {")
    w("    Record = 0,")
    w("    Counter = 1,")
    w("    Latched = 2,")
    w("};")
    w("")
    w("/// One code: its slot in the diag table and its fixed attributes.")
    w("struct Code {")
    w("    uint8_t slot;       ///< Dense index into the diag slot table")
    w("    Source source;")
    w("    uint16_t code;      ///< Unique within its source")
    w("    Severity severity;")
    w("    CodeKind kind;")
    w("    bool clears;        ///< Has an `active` bit cleared by DIAG_CLEAR on recovery")
    w("    const char *name = nullptr;")
    w("    bool blocks_arm = false;")
    w("    bool disarms = false;")
    w("};")
    w("")
    w("namespace codes {")
    by_source: dict[str, list[tuple[int, dict]]] = {}
    for slot, c in enumerate(live):
        by_source.setdefault(c["source"], []).append((slot, c))
    for s in sources:
        src = s["name"]
        entries = by_source.get(src)
        if not entries:
            continue
        w("")
        w(f"namespace {src} {{")
        for slot, c in entries:
            w(f"/// {c['description']}")
            if c["kind"] == "record":
                w(f"/// arg0: {c['arg0']}. arg1: {c['arg1']}.")
            sev = SEVERITIES[c["severity"]][0]
            kind = KINDS[c["kind"]]
            clears = "true" if c["clears"] else "false"
            w(
                f"inline constexpr Code k{c['name']}{{{slot}, Source::{pascal(src)}, "
                f"0x{c['code']:04X}, Severity::{sev}, CodeKind::{kind}, {clears}, {cpp_string(c['name'])}, {str(c['blocks_arm']).lower()}, {str(c['disarms']).lower()}}};"
            )
        w(f"}} // namespace {src}")
    w("")
    w("} // namespace codes")
    w("")
    w(f"inline constexpr size_t kSlotCount = {len(live)};")
    w("")
    w("/// Every live code, indexed by slot.")
    w("inline constexpr std::array<Code, kSlotCount> kCodeTable = {{")
    for c in live:
        w(f"    codes::{c['source']}::k{c['name']},")
    w("}};")
    w("")
    w("} // namespace drivelink::protocol::defs::diag")
    return finish(out)


# -- types ---------------------------------------------------------------------


def type_header_name(t: dict) -> str:
    return f"type_{t['ns']}.hpp"


def slot_text(item: dict, key: str) -> str:
    """The hex bits of a limit or default, with the f32 decimal in a comment."""
    bits = item[f"{key}_bits"]
    text = f"0x{bits:08X}"
    if item["type"] == "f32" and (item[key] is not None):
        text += f" /* {item[key]:.9g} */"
    return text


def flags_expr(item: dict) -> str:
    if not item["flags"]:
        return "flagBits()"
    return "flagBits(" + ", ".join(f"ItemFlag::{'Source' if f == 'source' else FLAG_ENUM[f]}" for f in item["flags"]) + ")"


def gen_type(t: dict) -> str:
    live = [i for i in t["items"] if not i["retired"]]
    retired = [i for i in t["items"] if i["retired"]]
    out = header(f"protocol/defs/{t['type']}.yaml")
    w = out.append
    w("#include <array>")
    w("#include <cstdint>")
    w("")
    w('#include "drivelink/protocol/defs.hpp"')
    w("")
    w(f"namespace drivelink::protocol::defs::{t['ns']} {{")
    w("")
    if t["description"]:
        w(f"/// {t['description']}")
    w(f"/// Module type id of {t['type']}.")
    w(f"inline constexpr uint8_t kTypeId = 0x{t['type_id']:02X};")
    w("")
    for i in live:
        w(f"/// {i['kind']} {i['name']}" + (f": {i['description']}" if i["description"] else ""))
        w(f"inline constexpr uint16_t k{pascal(i['name'])} = 0x{i['id']:04X};")
    if retired:
        w("")
        w("// Retired ids, never reused: " + ", ".join(f"0x{i['id']:04X} {i['name']}" for i in retired))
    w("")

    w("namespace detail {")
    for i in live:
        if i["values"]:
            w(f"inline constexpr std::array<EnumValue, {len(i['values'])}> kValues{i['id']:04X}{{{{")
            for v in i["values"]:
                w(f"    {{{cpp_string(v['name'])}, {v['value']}}},")
            w("}};")
        for key, label in (("args", "Args"), ("results", "Results")):
            if i[key]:
                w(f"inline constexpr std::array<ActionArg, {len(i[key])}> k{label}{i['id']:04X}{{{{")
                for a in i[key]:
                    w(f"    {{{cpp_string(a['name'])}, ValueType::{TYPE_ENUM[a['type']]}, {cpp_string(a['unit'])}}},")
                w("}};")
    w("} // namespace detail")
    w("")

    if live:
        w(f"inline constexpr std::array<ItemDesc, {len(live)}> kItems{{{{")
    else:
        w("inline constexpr std::array<ItemDesc, 0> kItems{};")
    for i in live:
        hid = f"{i['id']:04X}"
        w("    ItemDesc{")
        w(f"        .id = 0x{i['id']:04X},")
        w(f"        .kind = ItemKind::{KIND_ENUM[i['kind']]},")
        w(f"        .type = ValueType::{TYPE_ENUM[i['type']]},")
        w(f"        .flags = {flags_expr(i)},")
        w(f"        .name = {cpp_string(i['name'])},")
        w(f"        .unit = {cpp_string(i['unit'])},")
        w(f"        .description = {cpp_string(i['description'])},")
        w(f"        .min_bits = {slot_text(i, 'min')},")
        w(f"        .max_bits = {slot_text(i, 'max')},")
        w(f"        .default_bits = {slot_text(i, 'default')},")
        w(f"        .has_min = {'true' if i['has_min'] else 'false'},")
        w(f"        .has_max = {'true' if i['has_max'] else 'false'},")
        w(f"        .enum_values = {('detail::kValues' + hid) if i['values'] else '{}'},")
        w(f"        .ref = {cpp_string(i['ref']) if i['ref'] else 'nullptr'},")
        w(f"        .runs_in = ActionPlacement::{PLACEMENT_ENUM[i['runs_in']]},")
        w(f"        .args = {('detail::kArgs' + hid) if i['args'] else '{}'},")
        w(f"        .results = {('detail::kResults' + hid) if i['results'] else '{}'},")
        w(f"        .blob = BlobDir::{BLOB_ENUM[i['blob']]},")
        w("    },")
    if live:
        w("}};")
    w("")
    loops = ", ".join(f"LoopClass::{LOOP_ENUM[lp]}" for lp in t["loops"])
    w("inline constexpr TypeDesc kDesc{")
    w(f"    .name = {cpp_string(t['type'])},")
    w("    .type_id = kTypeId,")
    w(f"    .loops = loopMask({loops}),")
    w("    .items = kItems,")
    w("};")
    w("")
    w(f"static_assert(itemIdsUnique(kItems), \"two items of {t['type']} share an id\");")
    w("")
    w(f"}} // namespace drivelink::protocol::defs::{t['ns']}")
    return finish(out)


def gen_types(defs: dict) -> str:
    types = defs["types"]
    out = header("protocol/defs/*.yaml (the module types)")
    w = out.append
    w("#include <array>")
    w("")
    w('#include "drivelink/protocol/defs.hpp"')
    for t in types:
        w(f'#include "{type_header_name(t)}"')
    w("")
    w("namespace drivelink::protocol::defs {")
    w("")
    w("/// The system type (0x00, from system.yaml) and every module type, by type id.")
    if types:
        w(f"inline constexpr std::array<const TypeDesc *, {len(types)}> kTypeTable{{{{")
        for t in types:
            w(f"    &{t['ns']}::kDesc,")
        w("}};")
    else:
        w("inline constexpr std::array<const TypeDesc *, 0> kTypeTable{};")
    w("")
    w('static_assert(typeIdsUnique(kTypeTable), "two module types share a type id");')
    w("")
    w("} // namespace drivelink::protocol::defs")
    return finish(out)

