def describe(source: int, code: int) -> str:
    """Return "source.Name" for a (source, code) pair, or a hex placeholder."""
    src = SOURCES.get(source, f"source_0x{source:02X}")
    info = CODES.get((source, code))
    name = info["name"] if info else f"code_0x{code:04X}"
    return f"{src}.{name}"
